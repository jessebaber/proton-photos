package eu.akoos.photos.domain.vault

import kotlinx.coroutines.flow.Flow

/** Optional vault password store used at unlock and sign-out. */
interface VaultPassword {
    fun observeIsSet(): Flow<Boolean>
    suspend fun isSet(): Boolean
    suspend fun set(password: CharArray)
    suspend fun clear()
    suspend fun read(): CharArray?
    suspend fun matches(typed: CharArray): Boolean
}
